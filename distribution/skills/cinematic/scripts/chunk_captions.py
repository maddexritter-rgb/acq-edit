#!/usr/bin/env python3
"""Generate caption groups from the transcript as 1-3 word CHUNKS.

Measured: the reference keeps block width at ~0.71 of the card (p50) by showing only 1-3 words
at a time and REPLACING. Hand-authored long phrases ("if you had a" + a second line) pushed ours
to 0.92 and made every block feel heavy.
"""
import json, os, re, sys
D=os.path.dirname(os.path.abspath(__file__))
W=json.load(open(f"{D}/cut/timeline_words.json"))

# words that carry the beat -> big, own line, caps
# compound beats stay whole — "white room" must never split across chunks
# ⚠️ RETARGET THESE TWO PER CLIP — they are the only clip-specific lines in this file.
# EMPH_PHRASES: multi-word beats that must stay whole AND must swallow any word too short to
# render alone (a 0.020s "do" was its own cue once and never appeared — the phrase has to carry it).
# EMPH: the rare single beat words. Keep it to ~10% of lines; the reference is not flat but it is
# not shouty either.
EMPH_PHRASES=[("white","room"),("black","dot")]        # e.g. Alex: ("do","so","much","volume")
EMPH={"nothing","unreasonable"}                        # rare beats only
# soft / connective words that take the Didone italic accent voice
SERIF={"and","but","so","because","than","the","a","in","to","of","that","is","how","you"}

BREAK_BEFORE={"and","but","so","because","that","which","when","if","then","to","in","on",
              "for","with","you","we","they","it","there","what","how"}

def clean(w): return re.sub(r"[^A-Za-z0-9'$%.,?!-]","",w)

# 🛑 NO PUNCTUATION ON CAPTIONS. EVER. Editor ruling 2026-08-09. Commas, periods, question marks
# and exclamation marks never render. The chunker still READS punctuation to decide where a chunk
# breaks — it just never DISPLAYS it. Apostrophes stay (they are inside words: "there's", "won't").
def show(w): return re.sub(r"[.,?!;:]+", "", w)

groups=[]; i=0; n=len(W)
while i < n:
    chunk=[]
    # look ahead for a compound beat starting here
    def phrase_at(j):
        for ph in EMPH_PHRASES:
            got=[]; k=j
            for want in ph:
                while k<n and not clean(W[k]["word"]): k+=1
                if k>=n or clean(W[k]["word"]).lower().strip(".,?!")!=want: got=[]; break
                got.append((k,clean(W[k]["word"]))); k+=1
            if got: return got
        return None
    ph=phrase_at(i)
    if ph:
        idxs=[c[0] for c in ph]; words=[c[1] for c in ph]
        groups.append(dict(i0=idxs[0], i1=idxs[-1],
                           lines=[[(show(" ".join(words)).upper(), "peak")]],
                           cue_scale=1.20))          # whole line bumps together, per the locked spec
        i=idxs[-1]+1
        continue
    while i < n and len(chunk) < 4:
        w=clean(W[i]["word"])
        if not w: i+=1; continue
        if phrase_at(i) and chunk: break
        chunk.append((i,w)); i+=1
        if re.search(r"[.,?!]$", w): break          # punctuation closes a chunk
        if w.lower() in EMPH: break                 # a beat word closes its chunk
        nxt = clean(W[i]["word"]).lower() if i < n else ""
        if nxt in BREAK_BEFORE and len(chunk) >= 2: break
    if not chunk: continue
    idxs=[c[0] for c in chunk]; words=[c[1] for c in chunk]
    bare=[w.lower().strip(".,?!") for w in words]
    # 🛑 EMPHASIS = WEIGHT. Everything on ONE line at ONE size. Mixing sizes inside a line (and
    # then stacking them to make it fit) is what made the captions jump. Ladder from the locked
    # house spec: base Medium -> strong Bold -> emph Extrabold -> peak Black.
    def is_num(w): return bool(re.search(r"[0-9]", w)) or w.startswith("$")
    content=[k for k,b in enumerate(bare) if b not in SERIF]
    # the single longest content word carries the stress (deterministic director rule)
    lead = max(content, key=lambda k: len(bare[k])) if content else None
    runs=[]
    for k,w in enumerate(words):
        if bare[k] in EMPH:      st="peak"
        elif is_num(w):          st="emph"
        elif k==lead:            st="emph"
        elif bare[k] in SERIF:   st="base"
        else:                    st="strong"
        runs.append((show(w),st))
    merged=[]
    for t,st in runs:
        if merged and merged[-1][1]==st: merged[-1]=(merged[-1][0]+" "+t, st)
        else: merged.append((t,st))
    lines=[merged]                                   # ONE line. never stack.
    cue_scale = 1.15 if any(is_num(w) for w in words) else (1.10 if len(words)==1 else 1.0)
    groups.append(dict(i0=idxs[0], i1=idxs[-1], lines=lines, cue_scale=cue_scale))
print(f"{len(groups)} chunks from {n} words  (avg {n/len(groups):.1f} words/chunk)")
out=[]
for g in groups:
    out.append("        dict(i0=%d, i1=%d, lines=%r, cue_scale=%r)," % (g["i0"],g["i1"],g["lines"],g.get("cue_scale",1.0)))
open(f"{D}/generated_groups.py","w").write(
    "# AUTO-GENERATED by make_groups.py — 1-3 word chunks (reference grammar)\nGROUPS = [\n"
    + "\n".join(out) + "\n]\n")
for g in groups[:12]:
    print("   ", " | ".join(" ".join(r[0] for r in l) for l in g["lines"]))
